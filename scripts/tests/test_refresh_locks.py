"""Tests for scripts/refresh_locks.py (T-0033, TD-047): the weekly uv lock refresh."""
from __future__ import annotations

import importlib.util
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent.parent
BACKEND = ROOT / "backend"
_spec = importlib.util.spec_from_file_location("refresh_locks", ROOT / "scripts" / "refresh_locks.py")
assert _spec and _spec.loader
refresh_locks = importlib.util.module_from_spec(_spec)
sys.modules["refresh_locks"] = refresh_locks
_spec.loader.exec_module(refresh_locks)


def test_every_requirements_in_and_the_pyproject_get_a_lock(tmp_path: Path) -> None:
    for name in ("pyproject.toml", "requirements-build.in", "requirements-docs.in", "other.in"):
        (tmp_path / name).write_text("", encoding="utf-8")
    assert refresh_locks.lock_targets(tmp_path) == [
        ("pyproject.toml", "requirements.lock"),
        ("requirements-build.in", "requirements-build.lock"),
        ("requirements-docs.in", "requirements-docs.lock"),
    ]


def test_the_real_backend_has_a_lock_for_every_source() -> None:
    targets = refresh_locks.lock_targets(BACKEND)
    assert ("pyproject.toml", "requirements.lock") in targets
    assert ("requirements-build.in", "requirements-build.lock") in targets
    for source, lock in targets:
        assert (BACKEND / source).is_file()
        assert (BACKEND / lock).is_file(), f"{lock} missing: run scripts/refresh_locks.py"


def test_the_headers_stay_the_documented_command() -> None:
    """A refresh only moves pins: each lock's header keeps the plain command."""
    readme = (BACKEND / "README.md").read_text(encoding="utf-8").replace("\\\n  ", "")
    for source, lock in refresh_locks.lock_targets(BACKEND):
        expected = refresh_locks.header_command(source, lock)
        header = (BACKEND / lock).read_text(encoding="utf-8").splitlines()[:2]
        assert header == [
            "# This file was autogenerated by uv via the following command:",
            f"#    {expected}",
        ]
        assert expected in readme


def test_the_compile_command_targets_the_image_platform() -> None:
    plain = refresh_locks.compile_command("pyproject.toml", "requirements.lock", upgrade=False)
    assert plain[:4] == ["uv", "pip", "compile", "pyproject.toml"]
    for flag in ("--generate-hashes", "--only-binary", "x86_64-manylinux_2_28", "3.12"):
        assert flag in plain
    assert plain[plain.index("-o") + 1] == "requirements.lock"
    assert "--upgrade" not in plain
    custom = plain[plain.index("--custom-compile-command") + 1]
    assert custom == refresh_locks.header_command("pyproject.toml", "requirements.lock")
    upgrade = refresh_locks.compile_command("pyproject.toml", "requirements.lock", upgrade=True)
    assert upgrade == [*plain, "--upgrade"]


def test_main_runs_uv_in_the_backend_for_every_lock(tmp_path: Path) -> None:
    (tmp_path / "pyproject.toml").write_text("", encoding="utf-8")
    (tmp_path / "requirements-build.in").write_text("", encoding="utf-8")
    calls: list[tuple[list[str], dict[str, Any]]] = []

    def run(command: list[str], **kwargs: Any) -> None:
        calls.append((command, kwargs))

    assert refresh_locks.main(["--backend", str(tmp_path), "--upgrade"], run=run) == 0
    assert [c[0][3] for c in calls] == ["pyproject.toml", "requirements-build.in"]
    assert all(c[0][-1] == "--upgrade" for c in calls)
    assert all(c[1] == {"cwd": tmp_path, "check": True} for c in calls)
    calls.clear()
    refresh_locks.main(["--backend", str(tmp_path)], run=run)
    assert all("--upgrade" not in c[0] for c in calls)
