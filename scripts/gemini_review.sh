#!/usr/bin/env bash
# Request the Gemini second-opinion review on a KERP pull request (kerp-run step 4b).
# Posts exactly one comment, "/gemini-review", on the given PR and nothing else.
# Usage: scripts/gemini_review.sh <pr-number>
# This is the only command the committed allow rule in .claude/settings.json permits;
# keep it this narrow: one numeric argument, fixed repo, fixed method, fixed body.
set -euo pipefail

if [[ $# -ne 1 || ! "$1" =~ ^[0-9]+$ ]]; then
  echo "usage: scripts/gemini_review.sh <pr-number>" >&2
  exit 2
fi

body=$'/gemini-review\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_'
exec gh api -X POST "repos/kingdonk-ops/Kerp-/issues/$1/comments" -f "body=$body" --jq .html_url
